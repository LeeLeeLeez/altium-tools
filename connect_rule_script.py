#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成「连接方式规则」DelphiScript（.pas + .PrjScr）。

用途
----
「叠层覆盖」只搬铜皮，改不了过孔的**逐层 Relief**（那是过孔自己的属性，
脚本层已实测够不到：见今天日志的"三连空"）。用户裁决改走**规则路线**：
给目标层加一条**按层作用域**的 Connect Style 规则，一次覆盖该层所有未打勾的过孔。

官方名字（全部已在 AD 二进制 / 类型库里确认存在，且 ScriptingSystem.dll 可见）
--------------------------------------------------------------------------
  Rule 工厂   : PCBServer.PCBRuleFactory(eRule_PolygonConnectStyle)
                                  / (eRule_PowerPlaneConnectStyle)
  规则接口    : IPCB_PolygonConnectStyleRule / IPCB_PowerPlaneConnectStyleRule
  连法属性    : ConnectStyle      值域 eDirectConnect / eReliefConnect / eNoConnect
  热焊盘参数  : ReliefAirGap / ReliefConductorWidth / ReliefEntries
                / PolygonReliefAngle / PowerPlaneReliefExpansion
  规则创建范式: 01-servers.md 的 PCBRuleFactory + 03-pcb-interfaces.md 3.6
                （Name / Scope1Expression / Scope2Expression / 参数 / Board.AddPCBObject）
  复核利器    : Board.FindDominantRuleForObject(Obj, RuleKind) -> IPCB_Rule
                （文档 03 第 75 行：返回对该对象实际生效的规则）

与 overwrite_script.py 的关系
-----------------------------
独立模块，自带完整模板（Altium 一次只加载一个 .pas，产物必须自包含）。
命名/归档/落盘约定与 swap_script.py / overwrite_script.py 保持一致。

安全性
------
产物有**两个入口**：
  ReportRules - 纯读，只 dump 现有 connect style 规则（用已证 API）
  ApplyRules  - 会**真的向板子加规则**，需人工在那个入口里执行
风险标识符（IPCB_*ConnectStyleRule / ConnectStyle / eRule_*ConnectStyle）**只出现在 ApplyRules**，
所以即使 ApplyRules 编译不过，ReportRules 仍可用。
"""
from __future__ import annotations

import os
import re
import shutil
import time

PRUNE_ERRORS: list = []
KEEP_SETS = 10
KEEP_BAKS = 20

STEM_PREFIX = "connect_rule"

# 连法 -> 产物里写死的枚举常量（这三个已在 ScriptingSystem.dll 里确认存在）
STYLES = {
    "direct": "eDirectConnect",
    "relief": "eReliefConnect",
    "noconnect": "eNoConnect",
    "no_connect": "eNoConnect",
    "no": "eNoConnect",
}


class RulePickError(ValueError):
    pass


def validate(name_a: str, style: str, obj_scope: str, rule_kind: str):
    a = (name_a or "").strip()
    if not a:
        raise RulePickError("目标层名不能为空")
    st = STYLES.get((style or "").strip().lower())
    if st is None:
        raise RulePickError("未知的连接方式 %r，可选 %s"
                            % (style, sorted(set(STYLES))))
    sc = (obj_scope or "").strip() or "IsVia"
    if "'" in sc:
        raise RulePickError("对象作用域不能含单引号（会破坏 Pascal 字符串）")
    kd = (rule_kind or "").strip().lower() or "polygon"
    if kd not in ("polygon", "plane", "both"):
        raise RulePickError("rule_kind 只能是 polygon / plane / both")
    return a, st, sc, kd


def default_stem() -> str:
    return "%s_%s" % (STEM_PREFIX, time.strftime("%Y%m%d_%H%M%S"))


_TEMPLATE = r'''{-----------------------------------------------------------------------------}
{ connect_rule - GENERATED by gui/altium_tools/connect_rule_script.py          }
{                                                                              }
{ Do not hand-edit this file: regenerate it from the generator (see the        }
{ project rule "changing a generated artefact means changing its generator").  }
{                                                                              }
{ Purpose                                                                      }
{   "Layer overwrite" moves copper only and therefore cannot change a via's     }
{   PER-LAYER Relief - that is a property of the via itself. The agreed route   }
{   is a LAYER-SCOPED connect-style rule for the target layer instead.          }
{                                                                              }
{   target layer : @@NAME_A@@                                                   }
{   connect style: @@STYLE_COMMENT@@                                            }
{   object scope : @@SCOPE@@                                                    }
{   rule kind(s) : @@KIND@@                                                     }
{                                                                              }
{ TWO ENTRY POINTS - run them from the Script IDE as separate runs             }
{   ReportRules : READ ONLY. Dumps the connect-style rules and what actually    }
{                 governs the selected via. Safe, changes nothing.              }
{   ApplyRules  : >>> ADDS A RULE TO THE BOARD <<<  Save the board yourself     }
{                 afterwards if you want it kept.                              }
{                                                                              }
{ Nothing here deletes or edits an existing rule. If a rule with our name       }
{ already exists, ApplyRules reports it and does nothing (idempotent).         }
{-----------------------------------------------------------------------------}
Var
    Board : IPCB_Board;

Const
    RULENAME = '@@STEM@@_@@NAME_A@@';

{---- proven: copied verbatim from the generated swap/overwrite scripts ----}
Function LayerByName(Nm : String; Var Ok : Boolean) : TLayer;
Var
    LayerStack : IPCB_LayerStack_V7;
    LayerObj   : IPCB_LayerObject_V7;
    LName      : String;
Begin
    Ok := False;
    Result := eTopLayer;
    If Board = Nil Then Exit;
    LayerStack := Board.LayerStack_V7;
    If LayerStack = Nil Then Exit;
    LayerObj := LayerStack.FirstLayer;
    While LayerObj <> Nil Do
    Begin
        Try LName := LayerObj.Name; Except LName := ''; End;
        If LName = Nm Then
        Begin
            Try
                Result := LayerObj.LayerID;
                Ok := True;
            Except
                Ok := False;
            End;
            Exit;
        End;
        LayerObj := LayerStack.NextLayer(LayerObj);
    End;
End;

{---- proven: same rule iteration the bridge uses in PCB_GetDiffPairRules ----}
Procedure DumpConnectRules(SL : TStringList);
Var
    It   : IPCB_BoardIterator;
    Rule : IPCB_Rule;
    N    : Integer;
Begin
    N := 0;
    It := Board.BoardIterator_Create;
    It.AddFilter_ObjectSet(MkSet(eRuleObject));
    It.AddFilter_LayerSet(AllLayers);
    It.AddFilter_Method(eProcessAll);
    Rule := It.FirstPCBObject;
    While Rule <> Nil Do
    Begin
        If (Rule.RuleKind = eRule_PolygonConnectStyle)
            Or (Rule.RuleKind = eRule_PowerPlaneConnectStyle) Then
        Begin
            Inc(N);
            SL.Add('[' + IntToStr(N) + '] kind=' + IntToStr(Ord(Rule.RuleKind))
                + '  name=' + Rule.Name
                + '  priority=' + IntToStr(Ord(Rule.Priority)));
            SL.Add('      scope1=' + Rule.Scope1Expression);
            SL.Add('      scope2=' + Rule.Scope2Expression);
            SL.Add('      desc=' + Rule.Descriptor);
        End;
        Rule := It.NextPCBObject;
    End;
    Board.BoardIterator_Destroy(It);
    SL.Add('connect-style rule count = ' + IntToStr(N));
End;

{---- proven (the bridge does exactly this) ----}
Procedure DumpSelectedObjectRules(SL : TStringList);
Var
    It  : IPCB_BoardIterator;
    Obj : IPCB_Primitive;
    Sel : IPCB_Primitive;
    SelN : Integer;
    Cnt  : Integer;
    Ptr  : IPCB_Primitive;
    R    : IPCB_Rule;
Begin
    SelN := Board.SelectecObjectCount;
    SL.Add('selected count = ' + IntToStr(SelN));
    If SelN <= 0 Then Exit;

    Sel := Board.SelectecObject[0];
    If Sel = Nil Then Exit;

    It := Board.BoardIterator_Create;
    It.AddFilter_ObjectSet(MkSet(eViaObject));
    It.AddFilter_LayerSet(AllLayers);
    It.AddFilter_Method(eProcessAll);
    Ptr := It.FirstPCBObject;
    While Ptr <> Nil Do
    Begin
        If (Ptr.x = Sel.x) And (Ptr.y = Sel.y) Then
        Begin
            SL.Add('--- selected via at (' + IntToStr(Ptr.x) + ',' + IntToStr(Ptr.y) + ') ---');
            Try
                R := Board.FindDominantRuleForObject(Ptr, eRule_PolygonConnectStyle);
                If R = Nil Then SL.Add('  governing PolygonConnectStyle = none')
                Else SL.Add('  governing PolygonConnectStyle = ' + R.Name
                    + ' | ' + R.Descriptor);
            Except SL.Add('  governing PolygonConnectStyle =?'); End;
            Try
                R := Board.FindDominantRuleForObject(Ptr, eRule_PowerPlaneConnectStyle);
                If R = Nil Then SL.Add('  governing PowerPlaneConnectStyle = none')
                Else SL.Add('  governing PowerPlaneConnectStyle = ' + R.Name
                    + ' | ' + R.Descriptor);
            Except SL.Add('  governing PowerPlaneConnectStyle =?'); End;
        End;
        Ptr := It.NextPCBObject;
    End;
    Board.BoardIterator_Destroy(It);
End;

{..............................................................................}
{ ReportRules - READ ONLY                                                     }
{..............................................................................}
Procedure ReportRules;
Var
    SL : TStringList;
Begin
    Board := PCBServer.GetCurrentPCBBoard;
    If Board = Nil Then
    Begin
        ShowMessage('No PCB document is active.');
        Exit;
    End;
    SL := TStringList.Create;
    SL.Add('connect_rule REPORT - ' + ExtractFileName(Board.FileName));
    SL.Add('target layer = @@NAME_A@@   style = @@STYLE_COMMENT@@');
    SL.Add('============================================================');
    SL.Add('--- all connect-style rules ---');
    DumpConnectRules(SL);
    SL.Add('============================================================');
    SL.Add('--- rules governing the selected object ---');
    DumpSelectedObjectRules(SL);
    SL.SaveToFile(ExtractFilePath(Board.FileName) + '@@STEM@@_report.txt');
    SL.Free;
    ShowMessage('Done: @@STEM@@_report.txt (read only).');
End;

{..............................................................................}
{ ApplyRules - >>> WRITES A RULE TO THE BOARD <<<                             }
{..............................................................................}
Procedure ApplyRules;
Var
    SL       : TStringList;
    It       : IPCB_BoardIterator;
    Rule     : IPCB_Rule;
    Existing : IPCB_Rule;
    PolyR    : IPCB_PolygonConnectStyleRule;
    PlaneR   : IPCB_PowerPlaneConnectStyleRule;
    L        : TLayer;
    Ok       : Boolean;
    Made     : Integer;
Begin
    Board := PCBServer.GetCurrentPCBBoard;
    If Board = Nil Then
    Begin
        ShowMessage('No PCB document is active.');
        Exit;
    End;

    SL := TStringList.Create;
    SL.Add('connect_rule APPLY - ' + ExtractFileName(Board.FileName));
    SL.Add('*** NOT SAVED YET - save the board yourself if you want to keep it ***');
    SL.Add('target layer = @@NAME_A@@   style = @@STYLE_COMMENT@@   scope = @@SCOPE@@');

    L := LayerByName('@@NAME_A@@', Ok);
    If Not Ok Then
    Begin
        SL.Add('!! target layer not found on this board - nothing done');
        SL.SaveToFile(ExtractFilePath(Board.FileName) + '@@STEM@@_apply.txt');
        SL.Free;
        ShowMessage('Target layer not found. See report.');
        Exit;
    End;
    SL.Add('target layer id = ' + IntToStr(Ord(L)));

    {--- idempotence: refuse to duplicate our own rule ---}
    Existing := Nil;
    It := Board.BoardIterator_Create;
    It.AddFilter_ObjectSet(MkSet(eRuleObject));
    It.AddFilter_LayerSet(AllLayers);
    It.AddFilter_Method(eProcessAll);
    Rule := It.FirstPCBObject;
    While Rule <> Nil Do
    Begin
        If Rule.Name = RULENAME Then Existing := Rule;
        Rule := It.NextPCBObject;
    End;
    Board.BoardIterator_Destroy(It);

    If Existing <> Nil Then
    Begin
        SL.Add('rule "' + RULENAME + '" already exists - nothing done.');
        SL.Add('  its descriptor: ' + Existing.Descriptor);
        SL.Add('to change it, delete it in Design > Rules first (or rename).');
        SL.SaveToFile(ExtractFilePath(Board.FileName) + '@@STEM@@_apply.txt');
        SL.Free;
        ShowMessage('Rule already exists - nothing changed.');
        Exit;
    End;

    Made := 0;
    PCBServer.PreProcess;
    Try
@@APPLY_BLOCKS@@
    Finally
        PCBServer.PostProcess;
    End;

    SL.Add('rules created = ' + IntToStr(Made));
    SL.Add('============================================================');
    SL.Add('--- connect-style rules AFTER ---');
    DumpConnectRules(SL);
    SL.SaveToFile(ExtractFilePath(Board.FileName) + '@@STEM@@_apply.txt');
    SL.Free;
    If Made > 0 Then
        ShowMessage('Created ' + IntToStr(Made) + ' rule(s). SAVE the board to keep them.')
    Else
        ShowMessage('Nothing created - see @@STEM@@_apply.txt');
End;
'''

POLY_BLOCK = r'''        {--- IPCB_PolygonConnectStyleRule ---}
        PolyR := PCBServer.PCBRuleFactory(eRule_PolygonConnectStyle);
        PolyR.Name := RULENAME;
        PolyR.Comment := 'created by connect_rule_script.py for @@NAME_A@@';
        PolyR.Scope1Expression := '@@SCOPE@@';
        PolyR.Scope2Expression := 'All';
        PolyR.ConnectStyle := @@STYLE_ENUM@@;
        PolyR.ReliefAirGap := @@AIRGAP_UNITS@@;
        PolyR.ReliefConductorWidth := @@CW_UNITS@@;
        PolyR.ReliefEntries := @@ENTRIES@@;
        Rule := PolyR;
        Board.AddPCBObject(Rule);
        Inc(Made);
        SL.Add('created PolygonConnectStyle rule for '@@NAME_A@@);
'''

