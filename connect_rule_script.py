PRJ = ("[Design]\r\nVersion=1.0\r\nHierarchyMode=0\r\n\r\n"
       "[Document1]\r\nDocumentPath=@@PASNAME@@\r\n")


def build_pas(name_a: str, style: str = "no", obj_scope: str = "IsVia",
              rule_kind: str = "both", air_gap_mils: int = 10,
              conductor_mils: int = 10, entries: int = 4,
              expansion_mils: int = 20, stem: str = "") -> str:
    """生成 .pas 正文（纯 ASCII；CRLF 由调用方负责）。"""
    a, st, sc, kd = validate(name_a, style, obj_scope, rule_kind)

    blocks = []
    if kd in ("polygon", "both"):
        blocks.append(POLY_BLOCK)
    if kd in ("plane", "both"):
        blocks.append(PLANE_BLOCK)

    out = _TEMPLATE
    # 内部单位 = 1/10000 mil。这里在 Python 侧预算好，
    # 产物里只出现整数字面量 —— 避免依赖 MilsToCoord（那是桥接 Utils.pas 的函数，
    # 独立脚本里未必存在；官方文档示例用了它，但两种可能都会被编译挡下）。
    u = lambda mils: int(round(float(mils) * 10000))
    subs = [
        ("@@NAME_A@@", a),
        ("@@STEM@@", stem or STEM_PREFIX),
        ("@@SCOPE@@", sc),
        ("@@KIND@@", kd),
        ("@@STYLE_ENUM@@", st),
        ("@@STYLE_COMMENT@@", "%s (%s)" % (style, st)),
        ("@@AIRGAP_UNITS@@", str(u(air_gap_mils))),
        ("@@CW_UNITS@@", str(u(conductor_mils))),
        ("@@ENTRIES@@", str(int(entries))),
        ("@@EXP_UNITS@@", str(u(expansion_mils))),
    ]
    # 🔴 顺序要紧：子块自己的占位符必须先替换，再把拼好的块塞进模板。
    #    反过来做（APPLY_BLOCKS 放最后）会让块内部 token 错过替换时机 —— 哨兵会报出来。
    blocks = ["".join(subs_run(b, subs)) for b in blocks]
    out = out.replace("@@APPLY_BLOCKS@@", "".join(blocks))
    out = "".join(subs_run(out, subs))
    left = sorted(set(re.findall(r"@@\w+@@", out)))
    if left:
        raise RulePickError("模板里还有未替换的占位符: " + ", ".join(left))
    return out


def subs_run(text: str, subs) -> list:
    """逐 token 替换，返回片段列表（便于 join，避免中间态被再次扫描）。"""
    for tok, val in subs:
        text = text.replace(tok, val)
    return [text]


def prune_old(out_dir: str, keep_sets: int = 0, keep_baks: int = 0,
              log=None) -> list:
    """把过旧的套件/备份**移动**到 _old/（不删除）。"""
    keep_sets = keep_sets or KEEP_SETS
    keep_baks = keep_baks or KEEP_BAKS
    moved = []
    try:
        names = os.listdir(out_dir)
    except OSError:
        return moved
    stems = sorted({m.group(1) for n in names
                    for m in [re.fullmatch(
                        re.escape(STEM_PREFIX) + r"_\d{8}_\d{6}\.(pas|PrjScr)", n)]
                    if m})
    victims = []
    if len(stems) > keep_sets:
        for st in stems[:-keep_sets]:
            for ext in (".pas", ".PrjScr"):
                victims.append(st + ext)
    baks = sorted((n for n in names if ".bak_" in n),
                  key=lambda n: (os.path.getmtime(os.path.join(out_dir, n)), n),
                  reverse=True)
    victims += baks[keep_baks:]
    if not victims:
        return moved
    dest = os.path.join(out_dir, "_old")
    os.makedirs(dest, exist_ok=True)
    for n in victims:
        src = os.path.join(out_dir, n)
        if not os.path.isfile(src):
            continue
        tgt = os.path.join(dest, n)
        if os.path.exists(tgt):
            tgt = os.path.join(dest, "%s.%d" % (n, int(time.time())))
        try:
            shutil.move(src, tgt)
            moved.append(n)
        except Exception as e:            # noqa: BLE001
            PRUNE_ERRORS.append("%s: %s" % (n, e))
    if log and moved:
        log("   归档 %d 个旧文件 -> _old/" % len(moved))
    return moved


def write_script(out_dir: str, name_a: str, style: str = "no",
                 obj_scope: str = "IsVia", rule_kind: str = "both",
                 air_gap_mils: int = 10, conductor_mils: int = 10,
                 entries: int = 4, expansion_mils: int = 20,
                 stem: str = "") -> tuple[str, str]:
    """生成 <stem>.pas + <stem>.PrjScr，返回两个路径。"""
    os.makedirs(out_dir, exist_ok=True)
    if not stem:
        stem = default_stem()
    pas = os.path.join(out_dir, stem + ".pas")
    prj = os.path.join(out_dir, stem + ".PrjScr")
    body = build_pas(name_a, style, obj_scope, rule_kind, air_gap_mils,
                     conductor_mils, entries, expansion_mils, stem=stem)
    body = body.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")
    with open(pas, "wb") as f:
        f.write(body.encode("ascii"))
    with open(prj, "wb") as f:
        f.write(PRJ.replace("@@PASNAME@@", stem + ".pas").encode("ascii"))
    prune_old(out_dir)
    return pas, prj


